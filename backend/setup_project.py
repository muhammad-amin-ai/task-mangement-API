def create_folders() -> None:
    for folder in FOLDERS:
        os.makedirs(folder, exist_ok=True)
        print(f"[dir]  {folder}/")


def create_files() -> None:
    for relative_path, content in FILES.items():
        if os.path.exists(relative_path):
            print(f"[skip] {relative_path} (already exists)")
            continue
        os.makedirs(os.path.dirname(relative_path) or ".", exist_ok=True)
        with open(relative_path, "w", encoding="utf-8") as f:
            f.write(content)
        print(f"[new]  {relative_path}")


def main() -> None:
    print("=== Generating Task Management API project skeleton ===")
    create_folders()
    create_files()
    print("=== Done. Fill in .env from .env.example, then run: ===")
    print("    pip install -r requirements.txt")
    print("    python init_database.py")
    print("    uvicorn app.main:app --reload")


if __name__ == "__main__":
    main()
